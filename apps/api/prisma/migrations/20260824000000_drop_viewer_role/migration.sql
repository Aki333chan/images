-- Удаление роли «Наблюдатель».
--
-- Ролей остаётся три: ГМ, Админ, Модератор. Право просто смотреть без права
-- что-либо сделать никому не пригодилось, а лишняя роль в списке — лишний
-- способ выдать доступ не тому.
--
-- PostgreSQL не умеет удалять значение из enum, поэтому тип пересоздаётся.
-- Порядок шагов важен: сначала переносим людей, потом снимаем DEFAULT (иначе
-- ALTER TYPE упрётся в него), потом меняем тип, и только затем возвращаем
-- DEFAULT уже на новом типе.

-- 1. Существующие наблюдатели становятся модераторами.
--    Понижать до полного отсутствия доступа нельзя: человек уже работает, и
--    молча отобрать у него вход хуже, чем оставить чуть больше прав.
--    Модератор — ближайшая роль снизу: смотрит серверы и ведёт тикеты.
UPDATE "users" SET "role" = 'MODERATOR' WHERE "role" = 'VIEWER';

-- 2. Снимаем значение по умолчанию: оно ссылается на старый тип.
ALTER TABLE "users" ALTER COLUMN "role" DROP DEFAULT;

-- 3. Пересоздаём тип без VIEWER.
ALTER TYPE "Role" RENAME TO "Role_old";
CREATE TYPE "Role" AS ENUM ('OWNER', 'ADMIN', 'MODERATOR');
ALTER TABLE "users"
    ALTER COLUMN "role" TYPE "Role" USING ("role"::text::"Role");
DROP TYPE "Role_old";

-- 4. Новое значение по умолчанию.
--    Раньше им был VIEWER, то есть «заведён, но ничего не может».
--    Теперь — MODERATOR: заводят людей именно модераторами, а роль выше
--    выдаёт ГМ осознанно.
ALTER TABLE "users" ALTER COLUMN "role" SET DEFAULT 'MODERATOR';
