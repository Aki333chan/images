-- Флаг «для этого сервера наши плагины не предлагать».
--
-- На сервер, а не на человека: решение «нам это не нужно» относится к серверу
-- и должно пережить смену того, кто им занимается. Обязательного companion
-- флаг не касается — тот ставится в любом случае.
--
-- Значение по умолчанию false: на всех существующих серверах предложение
-- останется включённым, как если бы его никто не отклонял.
ALTER TABLE "servers" ADD COLUMN "addons_dismissed" BOOLEAN NOT NULL DEFAULT false;
