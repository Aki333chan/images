import { SetMetadata } from '@nestjs/common';

export const AUDIT_REDACT_BODY = 'auditRedactBody';

/**
 * Полностью скрывает тело запроса в аудит-логе: вместо него пишется метка.
 *
 * Нужен там, где секретно не отдельное поле, а весь payload целиком —
 * например, настройки подключения к игровому серверу (приватный адрес через
 * туннель, порт, пароль, адрес companion-плагина). Пофамильный список
 * «чувствительных» ключей такие случаи не покрывает: стоит добавить в DTO
 * новое поле — и оно молча утечёт в лог.
 *
 * Сам факт вызова (кто, когда, какой роут, какой сервер) в аудите остаётся.
 */
export const AuditRedactBody = () => SetMetadata(AUDIT_REDACT_BODY, true);
