/**
 * Поиск по ключевым словам и названию.
 *
 * Совпадение по вхождению, а не точное: «котика» должно находить «кот».
 * Пустой запрос отдаёт весь каталог — ассистенту полезно увидеть, что вообще
 * есть, прежде чем рисовать самому.
 */
export function findAsciiArt(query: string): AsciiArtEntry[] {
  const needle = query.trim().toLocaleLowerCase('ru');
  if (!needle) return ASCII_ART_CATALOG;

  // Запрос может быть фразой («нарисуй кота»), поэтому сверяем и по словам.
  const words = needle.split(/[\s,.!?]+/).filter((w) => w.length >= 3);
  const matches = (entry: AsciiArtEntry) => {
    const haystack = [entry.title, entry.id, ...entry.keywords].map((v) =>
      v.toLocaleLowerCase('ru'),
    );
    return haystack.some(
      (h) => h.includes(needle) || needle.includes(h) || words.some((w) => h.includes(w) || w.includes(h)),
    );
  };

  return ASCII_ART_CATALOG.filter(matches);
}
