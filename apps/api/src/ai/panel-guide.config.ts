/**
 * Справка под права собеседника, компактной строкой на пункт.
 *
 * Пустой список — не ошибка: у человека может не быть ни одного из этих
 * прав. Тогда раздела в промпте просто не будет, и ассистент не станет
 * рассказывать про экраны, которых тот не увидит.
 */
export function panelGuideFor(has: (permission: string) => boolean): string[] {
  return PANEL_GUIDE.filter((e) => e.permission === null || has(e.permission)).map(
    (e) => `- ${e.what} — ${e.where}`,
  );
}
