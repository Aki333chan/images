/**
 * Где что лежит в панели.
 *
 * ЗАЧЕМ ЭТО ЕСТЬ. Половина обращений к ассистенту — не «сделай», а «где
 * посмотреть» и «почему у меня нет такой кнопки». Без этой справки он
 * отвечает по общим соображениям и сочиняет пункты меню, которых нет: для
 * модели «панель управления» — это усреднённая панель из обучающих данных,
 * а не наша.
 *
 * ПОЧЕМУ ОТДЕЛЬНО ОТ ИНСТРУМЕНТОВ. Инструмент — это то, что ассистент делает
 * сам. Здесь — то, что человек делает руками, и по большей части того, что
 * ассистенту недоступно вовсе: маркет, файлы, бэкапы, расписания. Список
 * возможностей панели шире списка его умений, и путать одно с другим не
 * стоит.
 *
 * ПРАВО РЯДОМ С ПУНКТОМ — не украшение. Подсказка фильтруется по правам
 * собеседника: рассказывать модератору про экран, которого он не откроет, —
 * значит отправить его искать несуществующее и потом объясняться. Право
 * null означает «доступно всем, кто вошёл».
 */
export interface PanelGuideEntry {
  /** Что человек хочет сделать — его словами, а не нашими. */
  what: string;
  /** Куда идти. Путь через интерфейс, как он выглядит на экране. */
  where: string;
  /** Право, без которого этого пункта у человека нет. */
  permission: string | null;
}

