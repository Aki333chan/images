// Резолвер тулчейнов: позволяет Gradle самому скачать нужный JDK, если его нет
// в системе. Без него сборка модуля paper падает на любой машине, где JDK 25
// не установлен вручную.
plugins {
    id("org.gradle.toolchains.foojay-resolver-convention") version "1.0.0"
}

rootProject.name = "aurum-guilds"

// ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ ПЛАГИН, А НЕ ЧАСТЬ COMPANION.
//
// Та же причина, по которой отдельным плагином сделана авторизация. Companion
// — это мост к панели: HTTP-сервер, тикеты, чтение чужих плагинов. У него уже
// набралось больше ролей, чем стоило бы одному плагину. Гильдии же — это
// самостоятельная игровая механика с собственными данными, собственным HUD,
// полутора десятками команд и постоянно работающей задачей отрисовки. Смешать
// их значило бы получить плагин, который нельзя ни выключить по частям, ни
// перезагрузить, не задев всё остальное.
//
// Управление гильдиями из панели при этом НЕ требует второго HTTP-сервера:
// AurumGuilds выставляет свой Java API через ServicesManager, а companion —
// у которого сервер и канал к панели уже есть — подключается к нему мостом.
// Ровно так же устроены Vault и наша же система авторизации.
//
// guilds-api — интерфейс для других плагинов (в первую очередь companion) и
//         типы данных. Отдельным модулем, чтобы companion собирался против
//         него, не таща внутрь реализацию.
// core  — вся логика без Bukkit: конфиг, хранилище, гильдии, пати,
//         содержимое HUD. Собирается и тестируется без сервера.
// paper — адаптер к Bukkit/Paper: команды, слушатели, сайдбар, меню,
//         мосты к LuckPerms, Vault и авторизации.
include("guilds-api", "core", "paper")

// Составная сборка: paper компилируется против событий нашей же системы
// авторизации (ovh.aurumgg:auth-events). Зависимость compileOnly и мягкая —
// без AurumAuth плагин работает, просто не узнаёт об удалении аккаунтов.
includeBuild("../auth-plugin")
