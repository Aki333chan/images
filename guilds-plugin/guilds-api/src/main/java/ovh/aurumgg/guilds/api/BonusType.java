package ovh.aurumgg.guilds.api;

/**
 * Что именно усиливает бонус гильдии.
 *
 * <h2>Почему перечисление, а не свободная строка</h2>
 *
 * Строкой набор был бы расширяемым без пересборки, но каждый бонус всё равно
 * должен кто-то ПРИМЕНЯТЬ — эффектом зелья, множителем в обработчике события.
 * Незнакомая строка означала бы бонус, который гильдия купила и который молча
 * ничего не делает. Перечисление превращает опечатку в ошибку ещё до выдачи.
 *
 * <h2>Как выбирался набор</h2>
 *
 * Только то, что достижимо штатным Bukkit API и не ломает игру:
 *
 * <ul>
 *   <li>скорость и добыча — обычные эффекты зелий, их же видит сам игрок;</li>
 *   <li>дроп и опыт — множители в обработчиках, где сервер и так уже
 *       принимает решение о выпадении.</li>
 * </ul>
 *
 * Сознательно нет ничего, что меняет урон или здоровье: усиление в бою — это
 * прямое преимущество одной группы игроков над другой, и продавать его за
 * деньги значит менять баланс сервера деньгами. Добыча и передвижение такого
 * не делают.
 */
public enum BonusType {

    /**
     * Скорость добычи блоков — эффект «Спешка».
     *
     * Величина — уровень эффекта (1, 2, 3…), а не множитель.
     */
    MINING_SPEED("Скорость добычи", "Спешка", Kind.EFFECT_LEVEL, 30),

    /**
     * Скорость передвижения — эффект «Скорость».
     *
     * Величина — уровень эффекта. Играбельны первый и второй: выше по земле
     * бегать уже тяжело, а с четвёртого-пятого сервер начинает отбрасывать
     * игрока назад собственной проверкой «moved too quickly». Потолок при этом
     * высокий — см. {@link #max()}, там же объяснено, почему.
     */
    MOVEMENT_SPEED("Скорость передвижения", "Скорость", Kind.EFFECT_LEVEL, 20),

    /**
     * Множитель выпадения из блоков.
     *
     * Считается от того, что выпало бы и так, то есть уже с учётом удачи и
     * зачарований. 1.0 — без изменений, 2.0 — вдвое больше.
     */
    BLOCK_DROPS("Добыча из блоков", "Блоки", Kind.MULTIPLIER, 30.0),

    /** Множитель выпадения из мобов. Считается так же, как из блоков. */
    MOB_DROPS("Добыча с мобов", "Мобы", Kind.MULTIPLIER, 30.0),

    /** Множитель получаемого опыта. */
    EXPERIENCE("Опыт", "Опыт", Kind.MULTIPLIER, 30.0);

    /** Как читать величину бонуса. */
    public enum Kind {
        /** Целый уровень эффекта зелья: 1, 2, 3. */
        EFFECT_LEVEL,
        /** Множитель к тому, что и так выпало бы: 1.0 — ничего не меняет. */
        MULTIPLIER
    }

    private final String title;
    private final String shortTitle;
    private final Kind kind;
    private final double max;

    BonusType(String title, String shortTitle, Kind kind, double max) {
        this.title = title;
        this.shortTitle = shortTitle;
        this.kind = kind;
        this.max = max;
    }

    /** Название для игрока и для панели. */
    public String title() {
        return title;
    }

    /**
     * Название для сайдбара — в одно слово.
     *
     * «Добыча из блоков ×1.5 · 6д» не влезает в узкую полосу справа: сайдбар
     * обрезается по ширине экрана, и первым уезжает как раз остаток времени,
     * ради которого строка и показывается. Полное название остаётся там, где
     * место есть, — в {@code /guild bonuses} и в панели.
     */
    public String shortTitle() {
        return shortTitle;
    }

    public Kind kind() {
        return kind;
    }

    /**
     * Потолок величины.
     *
     * <h2>Это предел техники, а не рекомендация по балансу</h2>
     *
     * Потолок отвечает на вопрос «что сервер переживёт», а не «что стоит
     * выдавать». Играбельные значения — множители до ×3 и эффекты первого-
     * второго уровня; всё, что выше, оставлено ради проверок на тестовом
     * сервере, где надо увидеть работу бонуса сразу, а не через час добычи.
     *
     * Что происходит у верхней границы, если всё-таки выдать:
     *
     * <ul>
     *   <li>множитель в тридцать раз превращает сломанный блок в десятки
     *       предметов — это десятки сущностей на каждый удар киркой, и
     *       увлёкшийся игрок с «Удачей» просадит tps сам;</li>
     *   <li>«Скорость» с пятого уровня начинает воевать с проверкой сервера
     *       «moved too quickly»: игрока отбрасывает назад, и выглядит это как
     *       лаг, а не как усиление;</li>
     *   <li>«Спешка» выше уровня пяти-шести уже ничего не меняет — блоки и так
     *       ломаются мгновенно.</li>
     * </ul>
     *
     * Потолок при этом обязателен и проверяется при каждой выдаче — из игры,
     * из панели и через API: без него опечатка в одном нуле у NPC-торговца
     * означала бы ×300 и сервер, забитый предметами.
     */
    public double max() {
        return max;
    }

    /** Минимальная осмысленная величина: множитель ниже единицы был бы штрафом. */
    public double min() {
        return kind == Kind.MULTIPLIER ? 1.0 : 1.0;
    }

    /** Разбор из строки без чувствительности к регистру. null — нет такого. */
    public static BonusType parse(String raw) {
        if (raw == null) return null;
        String key = raw.trim().toUpperCase(java.util.Locale.ROOT).replace('-', '_');
        for (BonusType type : values()) {
            if (type.name().equals(key)) return type;
        }
        return null;
    }
}
