package ovh.aurumgg.guilds.api;

/**
 * Что именно усиливает бонус гильдии.
 *
 * <h2>Почему перечисление, а не свободная строка</h2>
 *
 * Строкой набор был бы расширяемым без пересборки, но каждый бонус всё равно
 * должен кто-то ПРИМЕНЯТЬ — эффектом зелья, множителем в обработчике события.
 * Незнакомая строка означала бы бонус, который гильдия купила и который молча
 * ничего не делает. Перечисление превращает опечатку в ошибку ещё до выдачи.
 *
 * <h2>Как выбирался набор</h2>
 *
 * Только то, что достижимо штатным Bukkit API и не ломает игру:
 *
 * <ul>
 *   <li>скорость и добыча — обычные эффекты зелий, их же видит сам игрок;</li>
 *   <li>дроп и опыт — множители в обработчиках, где сервер и так уже
 *       принимает решение о выпадении.</li>
 * </ul>
 *
 * Сознательно нет ничего, что меняет урон или здоровье: усиление в бою — это
 * прямое преимущество одной группы игроков над другой, и продавать его за
 * деньги значит менять баланс сервера деньгами. Добыча и передвижение такого
 * не делают.
 */
public enum BonusType {

    /**
     * Скорость добычи блоков — эффект «Спешка».
     *
     * Величина — уровень эффекта (1, 2, 3…), а не множитель.
     */
    MINING_SPEED("Скорость добычи", Kind.EFFECT_LEVEL, 3),

    /**
     * Скорость передвижения — эффект «Скорость».
     *
     * Величина — уровень эффекта. Выше второго уровня по земле бегать
     * практически невозможно, поэтому предел низкий.
     */
    MOVEMENT_SPEED("Скорость передвижения", Kind.EFFECT_LEVEL, 2),

    /**
     * Множитель выпадения из блоков.
     *
     * Считается от того, что выпало бы и так, то есть уже с учётом удачи и
     * зачарований. 1.0 — без изменений, 2.0 — вдвое больше.
     */
    BLOCK_DROPS("Добыча из блоков", Kind.MULTIPLIER, 3.0),

    /** Множитель выпадения из мобов. Считается так же, как из блоков. */
    MOB_DROPS("Добыча с мобов", Kind.MULTIPLIER, 3.0),

    /** Множитель получаемого опыта. */
    EXPERIENCE("Опыт", Kind.MULTIPLIER, 3.0);

    /** Как читать величину бонуса. */
    public enum Kind {
        /** Целый уровень эффекта зелья: 1, 2, 3. */
        EFFECT_LEVEL,
        /** Множитель к тому, что и так выпало бы: 1.0 — ничего не меняет. */
        MULTIPLIER
    }

    private final String title;
    private final Kind kind;
    private final double max;

    BonusType(String title, Kind kind, double max) {
        this.title = title;
        this.kind = kind;
        this.max = max;
    }

    /** Название для игрока и для панели. */
    public String title() {
        return title;
    }

    public Kind kind() {
        return kind;
    }

    /**
     * Потолок величины.
     *
     * Не вкусовщина, а защита: множитель в тысячу превращает одну шахту в
     * сервер, забитый предметами, а «Спешка X» ломает добычу как механику.
     * Проверяется при выдаче — и из игры, и из панели, и через API.
     */
    public double max() {
        return max;
    }

    /** Минимальная осмысленная величина: множитель ниже единицы был бы штрафом. */
    public double min() {
        return kind == Kind.MULTIPLIER ? 1.0 : 1.0;
    }

    /** Разбор из строки без чувствительности к регистру. null — нет такого. */
    public static BonusType parse(String raw) {
        if (raw == null) return null;
        String key = raw.trim().toUpperCase(java.util.Locale.ROOT).replace('-', '_');
        for (BonusType type : values()) {
            if (type.name().equals(key)) return type;
        }
        return null;
    }
}
