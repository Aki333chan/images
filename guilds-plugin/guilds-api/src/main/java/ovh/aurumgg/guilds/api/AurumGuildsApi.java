package ovh.aurumgg.guilds.api;

import java.util.List;
import java.util.Optional;
import java.util.UUID;
import java.util.concurrent.CompletableFuture;

/**
 * Публичный API AurumGuilds.
 *
 * <h2>Зачем он существует</h2>
 *
 * Управлять гильдиями нужно не только из игры, но и из панели. Заводить ради
 * этого второй HTTP-сервер в новом плагине было бы дублированием: у companion
 * сервер, токен и канал к панели уже есть и уже проверены. Поэтому AurumGuilds
 * регистрирует эту реализацию в ServicesManager, а companion берёт её оттуда и
 * работает мостом — ровно тот же приём, каким companion уже пользуется для
 * Vault, LuckPerms и нашей системы авторизации.
 *
 * Заодно это означает, что чужой плагин не полезет в базу гильдий напрямую:
 * схема таблиц остаётся внутренним делом AurumGuilds.
 *
 * <h2>Потоки</h2>
 *
 * Читающие методы, которые нужны каждый тик ({@link #membership(UUID)},
 * {@link #party(UUID)}), отвечают из памяти и синхронно — их можно звать с
 * главного потока. Всё, что ходит в базу или меняет состояние, возвращает
 * future и выполняется в рабочем потоке плагина.
 *
 * <h2>Чего здесь намеренно нет</h2>
 *
 * Нет методов «создать гильдию за игрока» и «пригласить». Создание и набор —
 * это решения самих игроков, и делать их из панели значило бы завести способ
 * записать человека в гильдию без его ведома. Из панели доступно ровно то же,
 * что администратору в игре: посмотреть и вмешаться (исключить, передать
 * лидерство, распустить).
 */
public interface AurumGuildsApi {

    // ----------------------------------------------------------- чтение

    /**
     * Гильдии для списка, с поиском по имени и тегу.
     *
     * @param query подстрока имени или тега; пусто или null — все гильдии
     * @param limit сколько максимум вернуть
     */
    CompletableFuture<List<GuildSummary>> guilds(String query, int limit);

    /** Гильдия целиком, включая состав. Пусто — такой гильдии нет. */
    CompletableFuture<Optional<GuildDetail>> guild(long guildId);

    /**
     * В какой гильдии состоит игрок.
     *
     * СИНХРОННО И ИЗ ПАМЯТИ: это спрашивают на каждом сообщении в чат и на
     * каждом обновлении HUD. Поход в базу на такой частоте убил бы главный
     * поток.
     */
    Optional<GuildMembership> membership(UUID playerUuid);

    /** Пати игрока. Тоже синхронно: пати вообще существует только в памяти. */
    Optional<PartyView> party(UUID playerUuid);

    /** История операций с банком гильдии, новые сверху. */
    CompletableFuture<List<GuildBankEntry>> bankHistory(long guildId, int limit);

    // ------------------------------------------------- вмешательство ГМ

    /**
     * Распустить гильдию помимо воли лидера.
     *
     * @param actor кто это сделал — попадёт в лог сервера
     */
    CompletableFuture<GuildActionResult> adminDisband(long guildId, String actor);

    /** Назначить лидером указанного участника этой же гильдии. */
    CompletableFuture<GuildActionResult> adminTransfer(long guildId, String targetName, String actor);

    /**
     * Убрать игрока из его гильдии, какой бы она ни была.
     *
     * Гильдию искать не нужно: игрок состоит максимум в одной. Если убираемый
     * оказался лидером, лидерство переходит следующему по старшинству, а
     * гильдия распускается только если после этого не осталось никого.
     */
    CompletableFuture<GuildActionResult> adminRemove(String targetName, String actor);

    // ------------------------------------------------------------ бонусы
    //
    // ЭТО ЖЕ И ТОЧКА ВХОДА ДЛЯ ЧУЖИХ ПЛАГИНОВ — например, для торговца-NPC,
    // который продаёт усиления гильдиям. Плагин берёт этот интерфейс из
    // ServicesManager, сам решает вопрос оплаты и зовёт grantBonus. Никакого
    // отдельного протокола, событий или доступа к базе для этого не нужно:
    // достаточно compileOnly-зависимости на guilds-api.
    //
    // Проверять, что покупатель состоит в гильдии и вправе за неё платить, —
    // дело вызывающего: AurumGuilds не знает, кто и за что берёт деньги, и
    // выдаёт бонус тому, на кого указали.

    /**
     * Действующие бонусы гильдии, истёкшие отброшены.
     *
     * СИНХРОННО И ИЗ ПАМЯТИ: величины спрашивают в обработчиках дропа и опыта,
     * то есть на каждый сломанный блок и каждого убитого моба.
     */
    List<GuildBonus> bonuses(long guildId);

    /**
     * Бонус игрока по его гильдии — то же, что {@link #bonuses(long)}, но по
     * игроку и с уже выбранным типом.
     *
     * Пусто — нет гильдии, нет такого бонуса или он истёк. Тоже синхронно.
     */
    Optional<GuildBonus> bonusOf(UUID playerUuid, BonusType type);

    /**
     * Выдать или продлить бонус.
     *
     * Повторная выдача того же вида ЗАМЕНЯЕТ прежний, а не складывается с ним:
     * иначе выгоднее было бы купить пять слабых бонусов вместо одного
     * сильного, и получилась бы гонка вместо выбора.
     *
     * @param magnitude величина; выше {@link BonusType#max()} не примут
     * @param duration  сколько действовать; null — навсегда
     * @param actor     кто выдал: ник администратора, «панель» или имя плагина
     */
    CompletableFuture<GuildActionResult> grantBonus(
            long guildId, BonusType type, double magnitude, java.time.Duration duration, String actor);

    /** Снять бонус досрочно. Отказ, если такого бонуса у гильдии нет. */
    CompletableFuture<GuildActionResult> revokeBonus(long guildId, BonusType type, String actor);

    // --------------------------------------------------- что вообще есть

    /**
     * Работает ли банк гильдий.
     *
     * false означает «на сервере нет Vault» — не поломку. Панель по этому
     * флагу просто не показывает баланс и операции с ним.
     */
    boolean bankAvailable();

    /**
     * Работают ли суффиксы к никам.
     *
     * false означает «на сервере нет LuckPerms». Гильдии при этом работают
     * полностью, просто тег не появляется рядом с ником.
     */
    boolean suffixesAvailable();
}
