package ovh.aurumgg.guilds.core;

import java.util.Locale;

/**
 * Что делать с общаком, когда гильдию распускают.
 *
 * <h2>Почему раньше вопроса не было, а теперь есть</h2>
 *
 * Пока банк был числом в нашей же таблице, при роспуске строка просто
 * удалялась: денег, которые могли бы куда-то деться, физически не
 * существовало — они появлялись только в момент снятия. Это было осознанное
 * «никуда не переводим», и разбирать его было нечего.
 *
 * На счёте {@code GUILD:<id>} в ledger лежат настоящие деньги. Удалить
 * гильдию и не тронуть счёт — значит оставить сумму на адресе, к которому
 * больше нет ни одной команды: в денежной массе сервера она есть, а достать
 * её нельзя. Поэтому судьбу общака теперь приходится называть явно, и раз
 * правила у серверов разные — она в конфиге.
 */
public enum BankOnDisband {

    /**
     * Всё лидеру. По умолчанию: роспуск — это его решение, получатель
     * единственный и заранее известен, проводка одна.
     */
    LEADER,

    /**
     * Поровну между участниками на момент роспуска, остаток от деления —
     * лидеру. Честнее всего к людям, которые в этот общак складывались.
     */
    SPLIT,

    /** В казну сервера. Ближе всего к прежнему поведению: деньги уходят из игры. */
    TREASURY,

    /**
     * Не трогать. Деньги останутся на счёте распущенной гильдии и будут
     * доступны только администратору через команды AurumCore — режим для тех,
     * кто хочет разбирать каждый случай руками.
     */
    KEEP;

    /**
     * Разбор мягкий: опечатка в конфиге не должна превращать роспуск в
     * исключение посреди удаления гильдии.
     */
    public static BankOnDisband parse(String raw) {
        if (raw == null) return LEADER;
        String key = raw.trim().toLowerCase(Locale.ROOT).replace('-', '_');
        for (BankOnDisband value : values()) {
            if (value.name().toLowerCase(Locale.ROOT).equals(key)) return value;
        }
        return LEADER;
    }

    public String storageName() {
        return name().toLowerCase(Locale.ROOT);
    }
}
