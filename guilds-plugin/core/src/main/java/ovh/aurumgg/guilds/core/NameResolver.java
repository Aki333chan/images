package ovh.aurumgg.guilds.core;

import java.util.UUID;

/**
 * Ник по UUID.
 *
 * Нужен потому, что тексты сообщений формируются здесь, рядом с условиями, при
 * которых они возникают, — а ключом везде служит UUID. Без резолвера пришлось
 * бы либо тащить ники сквозь всю логику, либо собирать сообщения в слое Bukkit,
 * то есть там, где их нельзя проверить тестом.
 *
 * Реализация в игре смотрит в сеть и в кэш сервера, в тестах — в обычную карту.
 */
@FunctionalInterface
public interface NameResolver {

    /** Ник или что-то узнаваемое, если ник неизвестен. Никогда не null. */
    String nameOf(UUID uuid);
}
