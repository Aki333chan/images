package ovh.aurumgg.guilds.core;

import java.util.random.RandomGenerator;

/**
 * Арифметика множителей бонусов.
 *
 * <h2>Бонус гильдии складывается с зачарованиями, а не заменяет их</h2>
 *
 * ЭТО ГЛАВНОЕ СВОЙСТВО, и оно обеспечивается не формулой, а выбором точки, где
 * формула применяется. Множитель считается от {@code amount} — от того, что
 * ВЫПАЛО БЫ И БЕЗ БОНУСА. Кирка с «Удачей III» уже превратила один алмаз в
 * три к моменту, когда сюда попадает число: события
 * {@code BlockDropItemEvent} и {@code EntityDeathEvent} несут добычу, которую
 * сервер посчитал сам, вместе с удачей, добычей и шёлковым касанием. У этих
 * событий даже нет ссылки на инструмент — значит, спорить о порядке нечего:
 * зачарование применено раньше, всегда.
 *
 * Поэтому «Удача III» и гильдейский ×1.5 дают примерно 4–5 алмазов, а не 1.5:
 * бонус умножает результат зачарования, а не сырую единицу. Гильдейское
 * усиление тем ценнее, чем лучше инструмент, — так и задумано.
 *
 * <h2>Дробная часть разыгрывается, а не округляется</h2>
 *
 * Множитель 1.5 на одном алмазе не может дать полтора алмаза. Округление вниз
 * означало бы, что купленный ×1.5 не делает НИЧЕГО для всего, что падает
 * поштучно, — а это почти вся ценная добыча. Округление вверх — что ×1.1
 * работает как ×2.
 *
 * Поэтому целая часть выдаётся всегда, а дробная разыгрывается: при ×1.5 к
 * каждой единице добавляется ещё одна с вероятностью 50%. На длинной дистанции
 * это ровно обещанные полтора раза, а на одном блоке — честная монетка.
 *
 * <h2>Почему это в core</h2>
 *
 * Здесь нет ни одного класса Bukkit, и генератор случайных чисел передаётся
 * снаружи — значит, и сложение с зачарованиями, и розыгрыш дробной части
 * проверяются обычным тестом, а не рассуждением о том, как оно должно бы
 * работать.
 */
public final class BonusMath {

    private BonusMath() {}

    /**
     * Сколько станет из {@code amount} после множителя.
     *
     * @param amount     сколько выпало бы без бонуса — уже с учётом зачарований
     * @param multiplier множитель бонуса; 1.0 и меньше ничего не меняет
     * @param random     чем разыгрывать дробную часть
     */
    public static int scaled(int amount, double multiplier, RandomGenerator random) {
        if (amount <= 0 || multiplier <= 1.0) return Math.max(amount, 0);

        double exact = amount * multiplier;
        int whole = (int) Math.floor(exact);
        double fraction = exact - whole;
        if (fraction > 0 && random.nextDouble() < fraction) whole++;
        return whole;
    }

    /**
     * Сколько ДОБАВИТЬ к тому, что уже выпало.
     *
     * Отдельным методом, потому что в событиях добавка выкидывается в мир
     * рядом с исходной стопкой, а не подменяет её: список уже созданных
     * сущностей менять нельзя.
     *
     * @return 0, если добавлять нечего
     */
    public static int extra(int amount, double multiplier, RandomGenerator random) {
        return Math.max(0, scaled(amount, multiplier, random) - amount);
    }
}
