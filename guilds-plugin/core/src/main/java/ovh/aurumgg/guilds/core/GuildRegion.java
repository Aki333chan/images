package ovh.aurumgg.guilds.core;

/**
 * Регион WorldGuard, привязанный к гильдии.
 *
 * <h2>Зачем хранить это у себя, а не спрашивать WorldGuard</h2>
 *
 * Вопрос «какие регионы принадлежат этой гильдии» из WorldGuard не задать: он
 * знает участников региона, но не знает, что эти участники — гильдия. Искать
 * регионы, где состав совпадает с составом гильдии, было бы гаданием: совпал
 * бы и любой регион, куда владелец вручную добавил тех же людей.
 *
 * Поэтому связь хранится явно. Она же и позволяет держать состав в согласии:
 * вступил человек в гильдию — добавляем его во все её регионы, вышел — убираем.
 *
 * @param guildId  гильдия
 * @param world    имя мира; регион уникален в пределах мира, а не сервера
 * @param regionId идентификатор региона в WorldGuard
 */
public record GuildRegion(long guildId, String world, String regionId) {}
