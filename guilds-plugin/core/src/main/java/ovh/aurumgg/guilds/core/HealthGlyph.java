package ovh.aurumgg.guilds.core;

/**
 * Здоровье участника пати — числом в процентах.
 *
 * <h2>Почему число, а не символ</h2>
 *
 * Сначала здесь был цветной кружок ●: пять ступеней цвета от зелёного к
 * красному. Читался он мгновенно, но отвечал только на вопрос «плохо или
 * нет» — а на практике нужен ответ точнее. «Зелёный» покрывает всё от 80 до
 * 100 процентов, и по нему не отличить целого человека от того, кому осталось
 * два удара.
 *
 * Число отвечает на оба вопроса сразу, если оставить ему цвет: «HP: 34%»
 * оранжевым читается и как «мало», и как «сколько именно».
 *
 * <h2>Почему ступеньками, а не плавно</h2>
 *
 * Плавного перехода в палитре Minecraft всё равно нет — доступно шестнадцать
 * цветов. Пять ступеней читаются однозначно, а больше означало бы, что игрок
 * пытается на глаз отличить жёлтый от оранжевого вместо того, чтобы смотреть
 * на бой.
 */
public final class HealthGlyph {

    /** Цвет для того, кого нет в сети: не «мёртв», а «неизвестно». */
    public static final String OFFLINE_COLOR = "&8";

    private HealthGlyph() {}

    /**
     * Код цвета по доле здоровья.
     *
     * @param percent 0..100; значения вне диапазона зажимаются, а не считаются
     *                ошибкой — источником тут служит деление на максимум HP,
     *                который у игрока с эффектами бывает и больше двадцати
     */
    public static String color(double percent) {
        double value = Math.max(0, Math.min(100, percent));
        if (value <= 0) return "&8";
        if (value >= 80) return "&a";
        if (value >= 60) return "&e";
        if (value >= 40) return "&6";
        if (value >= 20) return "&c";
        return "&4";
    }

    /**
     * Готовый индикатор для игрока в сети.
     *
     * Округление к ближайшему, но с одной оговоркой: живой игрок никогда не
     * показывается как «0%». Округлённая до нуля единица здоровья читается как
     * «уже труп», и союзник, которого ещё можно спасти, выглядел бы тем, к
     * кому бежать поздно.
     */
    public static String forHealth(double percent) {
        double value = Math.max(0, Math.min(100, percent));
        long shown = Math.round(value);
        if (shown == 0 && value > 0) shown = 1;
        return color(value) + "HP: " + shown + "%";
    }

    /**
     * Индикатор для того, кого нет в сети.
     *
     * «HP: ?», а не «не в сети» и не «HP: 0%»: ноль читался бы как «умирает»,
     * а связного текста в этой позиции нет — колонка должна начинаться с
     * одного и того же «HP: », иначе список перестаёт читаться сверху вниз.
     */
    public static String offline() {
        return OFFLINE_COLOR + "HP: ?";
    }

    /**
     * Доля здоровья в процентах.
     *
     * Максимум приходит от сервера и в теории бывает нулём (у игрока, которого
     * уже нет). Деление на ноль дало бы NaN, а NaN в сравнениях ведёт себя
     * так, что индикатор молча стал бы серым у всех.
     */
    public static double percent(double health, double maxHealth) {
        if (maxHealth <= 0) return 0;
        return Math.max(0, Math.min(100, health / maxHealth * 100));
    }
}
