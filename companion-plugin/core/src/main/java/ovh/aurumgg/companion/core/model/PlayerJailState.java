package ovh.aurumgg.companion.core.model;

/**
 * Сидит ли конкретный игрок — включая тех, кого сейчас нет на сервере.
 *
 * ЗАЧЕМ ОТДЕЛЬНО ОТ {@link JailsInfo}. Тот список принципиально содержит
 * только игроков в сети: признак «сидит» лежит в файле каждого игрока, и
 * собрать всех значило бы прочитать весь userdata — тысячи обращений к диску
 * на каждый показ страницы. Про ОДНОГО игрока спросить дёшево: это одно
 * обращение, и оно окупается там, где без ответа нельзя обойтись.
 *
 * А обойтись нельзя. Команда {@code togglejail} ведёт себя по-разному в
 * зависимости от того, сидит ли игрок уже: посадить не сидящего и продлить
 * срок сидящему — разные команды, а перевод в другую тюрьму EssentialsX
 * вообще запрещает. Панель обязана знать состояние ДО отправки команды, и
 * для офлайн-игрока узнать его больше неоткуда.
 *
 * @param known     EssentialsX знает такого игрока; false — он никогда не
 *                  заходил, и остальные поля бессмысленны
 * @param jailed    сидит прямо сейчас
 * @param jail      имя тюрьмы; пусто, если не сидит
 * @param releaseAt когда выпустят, миллисекунды эпохи; 0 — до отмены. Момента
 *                  посадки EssentialsX не хранит — см. {@link JailedPlayer}
 * @param online    игрок сейчас на сервере
 */
public record PlayerJailState(
        boolean known, boolean jailed, String jail, long releaseAt, boolean online) {

    /** Плагина нет, версия несовместима или такого игрока сервер не знает. */
    public static PlayerJailState unknown() {
        return new PlayerJailState(false, false, "", 0L, false);
    }
}
