package ovh.aurumgg.companion.core.model;

import java.util.List;

/**
 * Страница исторического списка игроков.
 *
 * <h2>Почему страница, а не весь список</h2>
 *
 * За годы работы сервер помнит тысячи имён, и отдавать их одним куском —
 * значит на каждое открытие вкладки собирать мегабайты JSON ради полусотни
 * строк на экране. Плюс ник из EssentialsX читается из файла игрока, то есть
 * ЗА КАЖДОГО отдельно: делать это для тысячи записей ради видимых пятидесяти
 * было бы тысячей лишних чтений с диска.
 *
 * Поэтому здесь и страница, и полное число — второе нужно, чтобы панель могла
 * честно сказать «показаны 50 из 1240», а не делать вид, что это весь список.
 *
 * @param players       записи этой страницы
 * @param total         сколько всего подошло под запрос
 * @param authAvailable есть ли плагин авторизации; false — делить не на что
 */
public record KnownPlayersPage(List<KnownPlayer> players, int total, boolean authAvailable) {}
