package ovh.aurumgg.auth.paper;

import org.bukkit.entity.Player;

/**
 * NPC — не игрок, хотя событие о нём приходит такое же.
 *
 * ЧТО ПРОИСХОДИТ БЕЗ ЭТОЙ ПРОВЕРКИ. Citizens и подобные плагины спавнят своих
 * NPC настоящими сущностями игрока и на каждого выбрасывают PlayerJoinEvent.
 * Через AsyncPlayerPreLoginEvent такой «игрок» при этом не проходит — его
 * никто не подключал, — поэтому состояния входа у него нет, и авторизация
 * считает его невошедшим. Дальше по обычному пути: NPC получает title
 * «войдите», а через минуту его КИКАЕТ по таймауту — то есть торговец,
 * охранник или проводник просто исчезает с сервера, и починить это можно
 * только перезапуском.
 *
 * Проверяется метаданные «NPC», а не класс: так помечает своих Citizens, и
 * это же читают все плагины авторизации. Зависимость на Citizens при этом не
 * нужна — метаданные видны через обычный Bukkit API, и на сервере без
 * Citizens проверка просто всегда ложна.
 */
final class Npcs {

    private Npcs() {}

    static boolean isNpc(Player player) {
        return player.hasMetadata("NPC");
    }
}
