package ovh.aurumgg.auth.core;

import java.time.Instant;

/**
 * Одна попытка входа — строка истории.
 *
 * ЗАПИСЫВАЮТСЯ И НЕУДАЧИ ТОЖЕ, и это главное. История нужна для разговора
 * «меня взломали»: успешные входы показывают, откуда заходили, а серия неудач
 * перед ними — что пароль перед этим подбирали. Одни успехи такой картины не
 * дают.
 *
 * @param at       когда
 * @param ip       откуда
 * @param result   чем закончилось
 * @param serverId с какого сервера сети — база одна на все, и без этого
 *                 непонятно, где именно человек заходил
 */
public record LoginRecord(Instant at, String ip, Result result, String serverId) {

    public enum Result {
        /** Вошёл по паролю. */
        SUCCESS,
        /** Пароль не подошёл. */
        WRONG_PASSWORD,
        /** Пароль верный, но не прошла двухфакторка. */
        WRONG_CODE,
        /** Пустили по сессии — пароль не спрашивали. */
        SESSION,
        /** Пустили без пароля: подтверждённый premium или право байпаса. */
        BYPASS,
        /** Сменил пароль по токену сброса. */
        RESET
    }
}
