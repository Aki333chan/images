package ovh.aurumgg.auth.core;

import java.util.UUID;

/**
 * Кому сообщить, что аккаунт исчез.
 *
 * <h2>Почему уведомление живёт здесь, а не в командах</h2>
 *
 * Удалить регистрацию можно двумя путями — сам игрок и администратор, — и
 * оба заканчиваются в {@link AuthService}. Если бы о событии сообщали
 * обработчики команд, то третий путь (а он появится: удаление из панели,
 * чистка неактивных) молча остался бы без уведомления, и обнаружилось бы это
 * по чужим данным, повисшим на несуществующем аккаунте.
 *
 * Интерфейс в core, а не в слое Bukkit, по той же причине, по какой здесь
 * живёт вся остальная логика: так уведомление проверяется обычным тестом.
 * Превращает его в событие Bukkit уже адаптер.
 *
 * <h2>Поток</h2>
 *
 * Вызывается ИЗ РАБОЧЕГО ПОТОКА, сразу после удаления из базы. Реализация
 * обязана сама перенести работу туда, где ей место: Bukkit API не
 * потокобезопасен.
 */
@FunctionalInterface
public interface AccountListener {

    /**
     * @param uuid     UUID удалённого аккаунта
     * @param username ник на момент удаления
     * @param byAdmin  true — удалил администратор, false — игрок удалил себя сам
     */
    void onAccountDeleted(UUID uuid, String username, boolean byAdmin);
}
