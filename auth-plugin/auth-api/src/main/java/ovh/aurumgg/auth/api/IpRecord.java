package ovh.aurumgg.auth.api;

import java.time.Instant;

/**
 * Один адрес, с которого заходил игрок.
 *
 * <h2>Зачем это вообще есть</h2>
 *
 * Сам плагин авторизации по этим данным ничего не решает — ни блокировок по
 * адресу, ни ограничений. Он их только записывает. Читает панель: когда
 * приходит жалоба «это мой брат, у нас один компьютер» или наоборот «этот
 * человек заходит с моего адреса», единственное, чем можно ответить, — список
 * адресов и даты.
 *
 * <h2>Первый и последний раз, а не журнал заходов</h2>
 *
 * На каждый адрес одна строка: когда увидели впервые и когда в последний. Не
 * запись на каждый вход — тех тысячи, и в них не видно главного: с одного
 * адреса человек играет год или зашёл однажды.
 *
 * Журнал самих входов существует отдельно ({@code /auth history}) и отвечает
 * на другой вопрос: что происходило в такой-то день.
 *
 * @param ip        адрес; IPv6 тоже, отсюда длина поля в 45 символов
 * @param firstSeen когда с него зашли впервые
 * @param lastSeen  когда в последний раз
 */
public record IpRecord(String ip, Instant firstSeen, Instant lastSeen) {}
