package ovh.aurumgg.auth.api;

import java.util.List;
import java.util.Optional;
import java.util.Set;
import java.util.UUID;
import java.util.concurrent.CompletableFuture;

/**
 * Публичный API системы авторизации.
 *
 * ЗАЧЕМ ОН ЕСТЬ. Companion-плагину (и любому другому коду на сервере) регулярно
 * нужно знать ровно одно: вошёл ли игрок прямо сейчас. Раньше на это отвечала
 * таблица AuthMe, в которую лазили напрямую SQL-запросом — то есть посторонний
 * плагин зависел от чужой схемы БД, которую никто не обещал не менять.
 *
 * Здесь вместо этого — маленький интерфейс, который AurumAuth регистрирует в
 * ServicesManager Bukkit. Тем же приёмом работает Vault: сам он денег не
 * хранит, но даёт интерфейс, за которым стоит настоящий плагин экономики.
 * Спрашивающему не нужно ни знать про MariaDB, ни держать её пароль.
 *
 * ВСЕ МЕТОДЫ БЕЗОПАСНО ЗВАТЬ С ГЛАВНОГО ПОТОКА: они отвечают по памяти и
 * никуда не ходят. Всё, что требует БД или bcrypt, происходит внутри плагина
 * асинхронно, а сюда попадает уже готовое состояние.
 */
public interface AurumAuthApi {

    /**
     * Версия контракта. Растёт, когда в интерфейс добавляется метод.
     *
     * Нужна тому, кто собран против старой версии api и работает с новой:
     * проверить число дешевле, чем ловить NoSuchMethodError.
     */
    int API_VERSION = 1;

    /**
     * Вошёл ли игрок прямо сейчас.
     *
     * Именно этот вопрос заменяет чтение isLogged из таблицы AuthMe. Для
     * игрока не в сети всегда false: «залогинен» — это состояние текущей
     * сессии, а не свойство аккаунта.
     */
    boolean isAuthenticated(UUID playerUuid);

    /**
     * Зарегистрирован ли аккаунт с таким ником (в сети игрок или нет).
     *
     * Единственный метод, который возвращает future, и по хорошей причине:
     * ответ на него лежит в базе, а не в памяти. Синхронная версия означала бы
     * поход в MariaDB с главного потока — ровно то, от чего мы уходили,
     * отказавшись читать чужую таблицу напрямую. Результат применять там, где
     * это уместно вызывающему; на главный поток он сам себя не вернёт.
     */
    CompletableFuture<Boolean> isRegistered(String username);

    /**
     * Подробное состояние игрока в сети.
     *
     * Пусто, если игрока нет на сервере. Отдельно от isAuthenticated,
     * потому что «не вошёл» и «вообще не подключён» — разные вещи, и
     * путать их в интерфейсе значит однажды перепутать их в коде.
     */
    Optional<AuthStatus> status(UUID playerUuid);

    /**
     * Результат premium-проверки для игрока в сети.
     *
     * Отдаётся как есть, вместе с честной границей своей достоверности —
     * см. пояснения в {@link PremiumVerdict}.
     */
    Optional<PremiumVerdict> premiumVerdict(UUID playerUuid);

    /**
     * Выдать игроку одноразовый токен для сброса пароля.
     *
     * ЕДИНСТВЕННЫЙ ПРИВИЛЕГИРОВАННЫЙ МЕТОД ЭТОГО API, и он такой намеренно.
     * Всё остальное здесь только читает состояние; этот — выдаёт путь к
     * чужому аккаунту, и вызывать его вправе лишь администраторский
     * инструмент (панель через companion, у которого свой bearer-токен на
     * порту, не смотрящем в интернет).
     *
     * Токен возвращается ОДИН раз и больше нигде не хранится в открытом виде:
     * в базе лежит только его хеш. Потерянный токен не восстанавливается —
     * выдаётся новый.
     *
     * Пусто, если аккаунта с таким ником нет. Асинхронный, потому что пишет
     * в базу.
     */
    /**
     * Адреса, с которых заходил игрок, — новые сверху.
     *
     * Для панели: сам плагин по этим данным ничего не решает. Пустой список
     * означает и «такого игрока нет», и «адресов за ним не записано» — для
     * показа это одно и то же.
     *
     * Асинхронно: поход в базу, а зовут отсюда в том числе главный поток.
     */
    CompletableFuture<List<IpRecord>> ipHistory(UUID playerUuid);

    /**
     * Ники всех зарегистрированных — в нижнем регистре.
     *
     * Нужен ОДИН запрос, а не проверка каждого игрока по отдельности: панель
     * делит исторический список из сотен ников на зарегистрированных и нет, и
     * сотня обращений к базе ради этого — не то, что стоит делать на открытие
     * вкладки.
     *
     * В нижнем регистре, потому что сравнивать всё равно придётся без учёта
     * регистра, и делать это на стороне вызывающего значит однажды забыть.
     */
    CompletableFuture<Set<String>> registeredUsernames();

    CompletableFuture<Optional<ResetToken>> issueResetToken(String username);
}
