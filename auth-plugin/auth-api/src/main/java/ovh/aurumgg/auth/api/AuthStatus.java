package ovh.aurumgg.auth.api;

/** Состояние игрока, находящегося в сети. */
public enum AuthStatus {

    /** Подключился, но пароль ещё не ввёл: движение, чат и команды заблокированы. */
    AWAITING_LOGIN,

    /** Аккаунта нет — ждём /register. */
    AWAITING_REGISTRATION,

    /**
     * Пароль принят, ждём код двухфакторки.
     *
     * Отдельное состояние: пароль уже проверен, но в игру пускать рано.
     * Слить его с AWAITING_LOGIN нельзя — тогда пришлось бы спрашивать пароль
     * заново, а с AUTHENTICATED тем более: второй фактор для того и включают,
     * чтобы одного пароля не хватало.
     */
    AWAITING_TOTP,

    /**
     * Токен сброса принят, ждём новый пароль.
     *
     * Отдельное состояние, а не «почти вошёл»: пока пароль не задан, игрок
     * остаётся заблокированным ровно так же, как до входа. Иначе сброс
     * превратился бы во вход без пароля.
     */
    AWAITING_NEW_PASSWORD,

    /** Ввёл пароль в этой сессии. */
    AUTHENTICATED,

    /**
     * Пароль не спрашивали: сессия ещё жива после недавнего переподключения.
     *
     * Отдельное значение, а не просто AUTHENTICATED: для доступа к игре разницы
     * нет, но при разборе инцидента важно видеть, вводили пароль в этот раз или
     * пустили по сессии.
     */
    AUTHENTICATED_BY_SESSION,

    /**
     * Пароль не спрашивали: вход подтверждён вышестоящим звеном (прокси в
     * online-mode). См. {@link PremiumVerdict#PREMIUM_VERIFIED}.
     */
    AUTHENTICATED_BY_PREMIUM,

    /**
     * Пароль не спрашивали: у игрока право aurumauth.bypass.
     *
     * Отдельным значением, чтобы такой вход был виден: на offline-сервере это
     * опасная настройка (UUID там считается из ника, и зашедший под чужим
     * ником получает чужие права), и в разборе инцидента важно отличать её от
     * настоящего входа по паролю.
     */
    AUTHENTICATED_BY_BYPASS;

    /** Пускать ли игрока в игру. */
    public boolean isAuthenticated() {
        return this == AUTHENTICATED
                || this == AUTHENTICATED_BY_SESSION
                || this == AUTHENTICATED_BY_PREMIUM;
    }
}
