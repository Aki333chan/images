package ovh.aurumgg.auth.api;

/**
 * Насколько мы уверены, что подключившийся — владелец лицензии.
 *
 * ГРАНИЦА ЧЕСТНОСТИ, КОТОРУЮ ВАЖНО НЕ РАЗМЫТЬ. Сервер работает в offline-mode,
 * иначе пиратские клиенты не подключатся вовсе. В offline-mode сервер НЕ
 * проверяет подпись сессии у Mojang — то есть криптографического доказательства
 * «это правда владелец аккаунта» на уровне протокола не существует в принципе.
 *
 * Поэтому запрос к Mojang API по нику отвечает ровно на один вопрос:
 * «существует ли лицензионная учётка с таким ником». Он НЕ отвечает на вопрос
 * «этот ли человек за клавиатурой». Пускать без пароля только на основании
 * существования ника — это открытая дверь: любой может подключиться под чужим
 * известным ником и войти. Именно поэтому такой ответ здесь — отдельное
 * значение {@link #PREMIUM_NAME_ONLY}, и пароль по нему НЕ пропускается.
 *
 * Единственный случай, когда пароль можно пропустить безопасно, —
 * {@link #PREMIUM_VERIFIED}: UUID подключения совпал с настоящим UUID из
 * Mojang. В offline-mode сервер сам вычисляет UUID из ника
 * (UUID.nameUUIDFromBytes("OfflinePlayer:" + ник) — так это делает ванильный
 * LoginListener), и совпасть с настоящим он не может. Значит, если UUID
 * настоящий, его подставило вышестоящее звено — прокси (Velocity/BungeeCord),
 * которое для этого игрока провело полноценную online-mode авторизацию.
 * Проверку сделали не мы, но её достоверность настоящая.
 *
 * На голом offline-сервере без прокси PREMIUM_VERIFIED не наступит никогда, и
 * это правильный способ ошибиться: пароль будет спрошен у всех.
 */
public enum PremiumVerdict {

    /**
     * UUID подключения совпал с UUID лицензионной учётки — вход уже подтверждён
     * вышестоящим звеном в online-mode. Пароль можно не спрашивать.
     */
    PREMIUM_VERIFIED,

    /**
     * Лицензионная учётка с таким ником существует, но подключение пришло с
     * offline-UUID. Это либо владелец лицензии, зашедший пиратским клиентом,
     * либо посторонний под чужим ником — различить их нечем.
     *
     * ПАРОЛЬ СПРАШИВАЕТСЯ ВСЕГДА. Значение существует не для того, чтобы кого-то
     * пускать, а чтобы это состояние было видно: по нему удобно, например,
     * предупреждать игрока, что ник занят лицензией.
     */
    PREMIUM_NAME_ONLY,

    /** Лицензионной учётки с таким ником нет — обычный оффлайн-игрок. */
    OFFLINE_NAME,

    /**
     * Спросить не удалось: Mojang не ответил, истёк таймаут, проверка выключена.
     *
     * Трактуется как «не premium»: недоступность внешнего сервиса не должна
     * превращаться в способ обойти пароль.
     */
    UNKNOWN;

    /** Можно ли по этому вердикту пропустить ввод пароля. */
    public boolean allowsPasswordBypass() {
        return this == PREMIUM_VERIFIED;
    }
}
