// Резолвер тулчейнов: позволяет Gradle самому скачать нужный JDK, если его нет
// в системе. Без него сборка модуля paper падает на любой машине, где JDK 25
// не установлен вручную.
plugins {
    id("org.gradle.toolchains.foojay-resolver-convention") version "1.0.0"
}

rootProject.name = "aurum-auth"

// ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ ПЛАГИН, А НЕ ЧАСТЬ COMPANION.
//
// Авторизация по своей природе — хирургическое вмешательство в самый ранний
// этап входа игрока: перехват join, движения, чата и команд на приоритетах,
// где ошибка видна не как «не работает функция», а как «сервер не пускает
// никого». Companion же делает прямо противоположное по характеру: держит
// HTTP-сервер, ходит в Vault и LuckPerms, шлёт тикеты в панель. Если там
// что-то однажды подвиснет (синхронный запрос, тяжёлая операция на главном
// потоке), это не должно иметь ни единого шанса задеть код входа.
//
// Ровно поэтому AuthMe — тоже отдельный узкоспециализированный плагин, а не
// часть большого «всё в одном».
//
// auth-api — крошечный интерфейс для других плагинов. Отдельным модулем, чтобы
//         companion собирался против него, не таща внутрь всю реализацию.
//         Имя с префиксом намеренно: этот модуль единственный, кого подключают
//         снаружи, и координаты «ovh.aurumgg:api» были бы слишком общими,
//         чтобы по ним что-то понять в чужом build-файле.
// core  — вся логика без Bukkit: конфиг, хранилище, bcrypt, сессии, троттлинг,
//         premium-эвристика. Собирается и тестируется без сервера.
// paper — адаптер к Bukkit/Paper: слушатели, команды, регистрация сервиса.
include("auth-api", "core", "paper")
